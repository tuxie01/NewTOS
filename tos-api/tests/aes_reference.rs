// ── round 2: the window manager, measured with a real reset ──────────────

/// The round-2 window dump, `tosdump/cases/aes-r2-wind.tsv` (78 cases, CRC
/// `AFB11C9F`) as the oracle answered it: EmuTOS 1a7484ab on Hatari's TT
/// (`docs/analysis/ORACLE.md`). Every case in
/// that table is preceded by the AES's own `wind_new` reset
/// (`aes/gemwmlib.c:1875-1893`), which is what makes handle allocation and
/// window geometry reproducible from case to case.
static DUMP_R2W: &[u8] = include_bytes!("../../tosdump/reference/EMUTOS-1a7484ab-AES-r2wind.BIN");

/// `int_out[0..7]` of the record whose case id is `id`, big-endian out of the
/// AES record form: 32-byte header, 120-byte records, case id at offset 0 and
/// `int_out[7]` at offset 76 (`tosdump/core/tosdump.h:105-121`).
fn r2w_intout(id: u16) -> [i16; harness::INTOUT_N] {
    let n = (DUMP_R2W.len() - harness::HDR_SIZE) / harness::REC_SIZE;
    let be16 = |r: &[u8], o: usize| (((r[o] as u16) << 8) | r[o + 1] as u16) as i16;
    for i in 0..n {
        let r = &DUMP_R2W[harness::HDR_SIZE + i * harness::REC_SIZE..][..harness::REC_SIZE];
        if be16(r, 0) as u16 == id {
            let mut out = [0i16; harness::INTOUT_N];
            for (k, v) in out.iter_mut().enumerate() {
                *v = be16(r, 76 + k * 2);
            }
            return out;
        }
    }
    panic!("case {id} is not in EMUTOS-1a7484ab-AES-r2wind.BIN");
}

/// One AES call, laid exactly as `tosdump/core/runner_aes.c` lays a prelude or
/// a measured call: poison everything but `global`, then the declared counts.
struct R2Call {
    opcode: i16,
    in_len: i16,
    out_len: i16,
    intin: &'static [i16],
}

/// Replay one round-2 case — the table's `!reset wind_new` first, then the
/// preludes, then the measured call — and hand back `int_out` as it stands.
fn r2w_replay(pb: &mut harness::Pb, prelude: &[R2Call], call: &R2Call) -> [i16; harness::INTOUT_N] {
    // `td_reset_aes(TD_AES_RESET_WIND_NEW, …)`: `wind_new` with all four
    // counts zero, poisoned like any other call (`core/runner_aes.c:126-134`).
    pb.poison();
    pb.call(109, 0, 0, 0, 0);
    for c in prelude {
        pb.poison();
        pb.intin[..c.intin.len()].copy_from_slice(c.intin);
        pb.call(c.opcode, c.in_len, c.out_len, 0, 0);
    }
    pb.poison();
    pb.intin[..call.intin.len()].copy_from_slice(call.intin);
    pb.call(call.opcode, call.in_len, call.out_len, 0, 0);
    *pb.intout
}

/// `wind_create` on a window table sized like the AES version we advertise.
///
/// EmuTOS ties `NUM_WIN` to `AES_VERSION`: **16** above 0x0320, 8 below
/// (`include/sysconf.h:26-35`), and handle 0 — the desktop window — is one of
/// the sixteen (`wm_init`, `aes/gemwmlib.c:1290`). Both machines report
/// `ap_version 0x0340`, so fifteen application handles must be available and
/// the sixteenth `wind_create` must fail. Measured: case 154 (the ninth
/// create) and case 170 (the sixteenth).
#[test]
fn wind_create_hands_out_fifteen_application_handles() {
    let _guard = harness::AES_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    harness::context();
    let mut pb = harness::Pb::new();

    const CREATE: R2Call =
        R2Call { opcode: 100, in_len: 5, out_len: 1, intin: &[0x0FEF, 0, 20, 320, 200] };
    let fill = [CREATE, CREATE, CREATE, CREATE, CREATE, CREATE, CREATE, CREATE];

    // Case 154: eight windows already created, the ninth create still succeeds.
    assert_eq!(r2w_replay(&mut pb, &fill, &CREATE), r2w_intout(154), "case 154");

    // Case 170: fifteen created, the sixteenth has no slot left.
    let mut fill15 = Vec::new();
    for _ in 0..15 {
        fill15.push(CREATE);
    }
    assert_eq!(r2w_replay(&mut pb, &fill15, &CREATE), r2w_intout(170), "case 170");

    pb.poison();
    pb.call(109, 0, 0, 0, 0); // leave the table as the reset left it
}

/// What `wind_create` and `wind_open` store in the four window rectangles.
///
/// `wm_create` puts the caller's rectangle in **WS_FULL only** and zeroes the
/// current and previous ones — `w_setsize(WS_CURR, i, &gl_rzero)`,
/// `w_setsize(WS_PREV, i, &gl_rzero)`, `w_setsize(WS_FULL, i, pt)`
/// (`aes/gemwmlib.c:1377-1380`). `wm_open` then lets `draw_change` shift the
/// old current rect into PREV and install the open rect as current
/// (`:1069-1077`), and *afterwards* overwrites PREV with the open rect as well
/// (`:1427`) — so an opened window reports the same rectangle for `WF_CXYWH`
/// and `WF_PXYWH`, and neither of them is the one `wind_create` was given.
///
/// Measured: cases 228/230/232 (created only) and 250/253/259 (after the open).
#[test]
fn window_rectangles_after_create_and_open_match_the_tt() {
    let _guard = harness::AES_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    harness::context();
    let mut pb = harness::Pb::new();

    const CREATE: R2Call =
        R2Call { opcode: 100, in_len: 5, out_len: 1, intin: &[0x0FEF, 10, 20, 300, 200] };
    const OPEN: R2Call =
        R2Call { opcode: 101, in_len: 5, out_len: 1, intin: &[1, 30, 40, 320, 240] };
    // `wind_get(1, field)` with OUT_LEN 5 — the rect arms write poutwds[0..3],
    // i.e. int_out[1..4] behind the return code (`aes/gemsuper.c:343`).
    let get = |field: i16| R2Call {
        opcode: 104,
        in_len: 2,
        out_len: 5,
        intin: if field == 7 {
            &[1, 7]
        } else if field == 6 {
            &[1, 6]
        } else {
            &[1, 5]
        },
    };

    for (id, field, prelude) in [
        (228u16, 7i16, &[CREATE][..]),   // WF_FXYWH: the create rect
        (230, 5, &[CREATE][..]),         // WF_CXYWH: gl_rzero
        (232, 6, &[CREATE][..]),         // WF_PXYWH: gl_rzero
        (250, 5, &[CREATE, OPEN][..]),   // WF_CXYWH: the open rect
        (253, 6, &[CREATE, OPEN][..]),   // WF_PXYWH: the open rect too
        (259, 7, &[CREATE, OPEN][..]),   // WF_FXYWH: untouched by the open
    ] {
        assert_eq!(
            r2w_replay(&mut pb, prelude, &get(field)),
            r2w_intout(id),
            "case {id} (wind_get field {field})"
        );
    }

    pb.poison();
    pb.call(109, 0, 0, 0, 0);
}

/// What `wind_close` leaves in the three rectangles it rewrites (A16).
///
/// `wm_close` does not simply drop `VF_ISOPEN`: it closes **through**
/// `draw_change(w_handle, &gl_rzero)` (`aes/gemwmlib.c:1449,1453`), and
/// `draw_change` rewrites `WS_PREV`, `WS_CURR` and `WS_WORK` before it even
/// tests `VF_ISOPEN` (`:1069-1077` against the shortcut at `:1085-1086`) —
/// `WS_PREV` takes the old `WS_CURR`, `WS_CURR` takes `pt` (here `gl_rzero`,
/// 0,0,0,0, `aes/gemgraf.c:425`) and `WS_WORK` is recomputed from `pt` with
/// `wm_calc(WC_WORK, kind, …)`. Only afterwards is the flag cleared (`:1454`).
///
/// The round-2 table has **no** case for this transition (its four close cases,
/// 188/190/193/194, read the return value only), so the oracle is the pinned
/// source — like [`wf_owner_answers_what_the_pinned_emutos_source_mandates`].
/// Nothing is written as a literal: the previous rectangle is read back with
/// `wind_get` before the close, and the closed work area is asked of the AES's
/// own `wm_calc` through `wind_calc(WC_WORK, kind, 0,0,0,0)` (opcode 108), so
/// the expectation follows the device's border metrics instead of freezing
/// them.
///
/// The window is **moved** after the open on purpose. `wm_open` overwrites
/// `WS_PREV` with the open rectangle (`:1427`, measured as case 253), so
/// without a move `WF_PXYWH` would read the same before and after the close and
/// could not tell a correct implementation from one that writes nothing. Each
/// of the three assertions is preceded by the check that its expectation really
/// differs from the pre-close state.
#[test]
fn window_rectangles_after_a_close_are_the_ones_draw_change_leaves() {
    let _guard = harness::AES_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    harness::context();
    let mut pb = harness::Pb::new();

    const KIND: i16 = 0x0FEF;
    const WF_WXYWH: i16 = 4;
    const WF_CXYWH: i16 = 5;
    const WF_PXYWH: i16 = 6;
    const WC_WORK: i16 = 1; // `include/aesdefs.h:556`

    const CREATE: R2Call =
        R2Call { opcode: 100, in_len: 5, out_len: 1, intin: &[KIND, 10, 20, 300, 200] };
    const OPEN: R2Call =
        R2Call { opcode: 101, in_len: 5, out_len: 1, intin: &[1, 30, 40, 320, 240] };
    // `wind_set(1, WF_CURRXYWH, 70, 90, 260, 180)` — `wm_set`'s `WF_CXYWH` arm
    // is `draw_change(w_handle, pinwds)` (`gemwmlib.c:1676-1678`), which is what
    // puts a *different* rectangle into `WS_CURR` than the one `wm_open` left
    // in `WS_PREV`.
    const MOVE: R2Call =
        R2Call { opcode: 105, in_len: 6, out_len: 1, intin: &[1, WF_CXYWH, 70, 90, 260, 180] };
    const CLOSE: R2Call = R2Call { opcode: 102, in_len: 1, out_len: 1, intin: &[1] };

    let get = |field: i16| -> R2Call {
        R2Call {
            opcode: 104,
            in_len: 2,
            out_len: 5,
            intin: match field {
                WF_WXYWH => &[1, WF_WXYWH],
                WF_CXYWH => &[1, WF_CXYWH],
                _ => &[1, WF_PXYWH],
            },
        }
    };

    let open_then_move: &[R2Call] = &[CREATE, OPEN, MOVE];
    let and_close: &[R2Call] = &[CREATE, OPEN, MOVE, CLOSE];

    // The state the close finds, read back rather than assumed.
    let before_curr = r2w_replay(&mut pb, open_then_move, &get(WF_CXYWH));
    let before_work = r2w_replay(&mut pb, open_then_move, &get(WF_WXYWH));
    assert_eq!(before_curr[0], 1, "the window must be there before the close");

    // `wm_calc(WC_WORK, kind, gl_rzero)` — the AES's own answer, not a literal.
    pb.poison();
    pb.intin[..6].copy_from_slice(&[WC_WORK, KIND, 0, 0, 0, 0]);
    pb.call(108, 6, 5, 0, 0);
    let zero_work = *pb.intout;

    // …and it has to differ from what the window had, or the assertion below
    // would hold for an implementation that leaves `WS_WORK` alone.
    assert_ne!(
        &zero_work[1..5],
        &before_work[1..5],
        "the closed work area must differ from the open one for this to discriminate"
    );
    assert_ne!(
        &before_curr[1..5],
        &[0i16, 0, 0, 0],
        "the window must have a non-zero rect before the close"
    );

    // WF_CXYWH — `gl_rzero`, the `pt` `wm_close` passes in (`:1449,1073`).
    assert_eq!(
        &r2w_replay(&mut pb, and_close, &get(WF_CXYWH))[..5],
        &[1, 0, 0, 0, 0],
        "WF_CXYWH after wind_close is gl_rzero (gemwmlib.c:1449,1073; gemgraf.c:425)"
    );

    // WF_PXYWH — the rectangle the window had when it was closed (`:1069-1070`).
    assert_eq!(
        &r2w_replay(&mut pb, and_close, &get(WF_PXYWH))[..5],
        &before_curr[..5],
        "WF_PXYWH after wind_close is the old WS_CURR (gemwmlib.c:1069-1070)"
    );

    // WF_WXYWH — recomputed from `gl_rzero` (`:1074-1077`), negative for a
    // bordered window; `wind_calc` above says what the metrics make of it.
    assert_eq!(
        &r2w_replay(&mut pb, and_close, &get(WF_WXYWH))[..5],
        &zero_work[..5],
        "WF_WXYWH after wind_close is wm_calc(WC_WORK, kind, 0,0,0,0) \
         (gemwmlib.c:1074-1077)"
    );

    pb.poison();
    pb.call(109, 0, 0, 0, 0);
}

/// `wind_get(WF_OWNER)` against the pinned source's measurement.
///
/// `WF_OWNER` (20) came into EmuTOS with `acb7f3b4` ("Add partial
/// implementation of WF_OWNER to wind_get", 2025-08-23), after the
/// `VERSION_1_4` tag: the `EMUTOS14-*` dumps recorded 1.4's `default: return
/// FALSE` plus four words of `xif`'s uninitialised `int_out`
/// (`aes/gemsuper.c:429,444-445`), `0, -1, 0, 0, 0` in both cases. The
/// reference is now the oracle built from the pinned source
/// (`EMUTOS-1a7484ab-AES-r2wind.BIN`, `docs/analysis/ORACLE.md`), which has
/// the arm at `aes/gemwmlib.c:1578-1589` under `#if AES_VERSION >= 0x330`:
/// `poutwds[0] = pwin->w_owner->p_pid` — the process that **created** the
/// window (`w_setup`, `:210`), which `wm_open` does not change —
/// `poutwds[1] = (w_flags & VF_ISOPEN) != 0`, `poutwds[2] = gl_wtop` (the raw
/// variable: `NIL` when nothing is open, `wm_init` `:1297`, `draw_change`
/// `:1093`) and `poutwds[3] = W_TREE[ROOT].ob_head`, the bottom-most open
/// window. The test asserts that the dump holds exactly those values, then
/// that NewTOS answers what the dump holds.
#[test]
fn wf_owner_answers_what_the_pinned_emutos_source_mandates() {
    let _guard = harness::AES_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let ctx = harness::context();
    let mut pb = harness::Pb::new();

    const CREATE: R2Call =
        R2Call { opcode: 100, in_len: 5, out_len: 1, intin: &[0x0FEF, 10, 20, 300, 200] };
    const OPEN: R2Call =
        R2Call { opcode: 101, in_len: 5, out_len: 1, intin: &[1, 30, 40, 320, 240] };
    const OWNER: R2Call = R2Call { opcode: 104, in_len: 2, out_len: 5, intin: &[1, 20] };

    // Case 244: created, never opened. Nothing is open, so gl_wtop is NIL and
    // the window tree root has no children. The owner is the creating
    // process, the application chain's pid 0 (`aes/geminit.c:850-877`).
    let want = r2w_intout(244);
    assert_eq!(&want[..5], &[1, 0, 0, -1, -1], "case 244 as the pinned source answers it");
    let got = r2w_replay(&mut pb, &[CREATE], &OWNER);
    assert_eq!(&got[..5], &want[..5], "WF_OWNER of a created, unopened window");
    assert_eq!(got[1], ctx.ap_id, "the owner is this application");

    // Case 247: the same window, opened. It is the only window, so it is both
    // the top and the bottom of the tree.
    let want = r2w_intout(247);
    assert_eq!(&want[..5], &[1, 0, 1, 1, 1], "case 247 as the pinned source answers it");
    let got = r2w_replay(&mut pb, &[CREATE, OPEN], &OWNER);
    assert_eq!(&got[..5], &want[..5], "WF_OWNER of an open window");

    pb.poison();
    pb.call(109, 0, 0, 0, 0);
}

/// The AES leaves the VDI's **string** input device in SAMPLE mode.
///
/// EmuTOS' scheduler polls the keyboard on every dispatcher pass — `chkkbd()`
/// (`aes/gemdisp.c:157-177`) — and reads the key through `gsx_char()`, which
/// opens with `intin = {4, 2}` + `gsx_ncode(SET_INPUT_MODE, 0, 2)`, i.e.
/// `vsin_mode(4, 2)` (`aes/gemgsxif.c:459-463`). The four device modes are
/// VDI globals (`vdi/vdi_defs.h:258`), not per-workstation fields, so that
/// write is observable to any application: `vqin_mode(4)` reports 1 instead
/// of the `vdimouse_init` default 0 (`vdi/vdi_mouse.c:575-578`).
///
/// That is what the reference TT reported, and this test compares against the
/// measurement rather than against a literal: it decodes `vqin_mode`'s
/// `INTOUT[0]` out of the two VDI dumps taken on that machine —
/// `EMUTOS-1a7484ab-VDI-r2.BIN` record 16 (case 51) and
/// `EMUTOS-1a7484ab-VDI-all.BIN` record 40 (case 77), the same query in two
/// independent runs (the `EMUTOS14-*` dumps of the real TT say the same).
///
/// It has to live in the **AES** binary: `tests/vdi_reference` deliberately
/// runs no AES and opens the physical workstation itself, and `v_opnwk` puts
/// all four devices back to REQUEST (`vdimouse_init`,
/// `vdi/vdi_control.c:563`), so 0 is the right answer there. This binary sets
/// up what the dumper had — `appl_init`, `graf_handle`, `v_opnvwk` on the
/// AES's physical handle — and `v_opnvwk` performs no such reset.
#[test]
fn aes_dispatch_leaves_the_string_device_in_sample_mode() {
    /// `vqin_mode`'s `INTOUT[0]` for `intin[0] = dev`, out of a VDI reference
    /// record: 32-byte header, 1592-byte records, `INTOUT` at offset 800,
    /// `INTIN` at 32, opcode at 2 (`tests/vdi_reference/harness.rs`).
    fn tt_vqin_mode(dump: &[u8], rec: usize, dev: i16) -> i16 {
        let r = &dump[32 + rec * 1592..][..1592];
        let be16 = |o: usize| (((r[o] as u16) << 8) | r[o + 1] as u16) as i16;
        assert_eq!(be16(2), 115, "record {rec} is not a vqin_mode call");
        assert_eq!(be16(32), dev, "record {rec} queried another device");
        be16(800)
    }

    static DUMP_R2: &[u8] = include_bytes!("../../tosdump/reference/EMUTOS-1a7484ab-VDI-r2.BIN");
    static DUMP_ALL: &[u8] = include_bytes!("../../tosdump/reference/EMUTOS-1a7484ab-VDI-all.BIN");

    let _guard = harness::AES_LOCK.lock().unwrap_or_else(|e| e.into_inner());

    // `appl_init` + `graf_handle` + `v_opnvwk`, the context the dumper ran in.
    // The `appl_init` trap alone already ran a dispatch.
    let ctx = harness::context();

    // Both runs of the reference TT, and the three devices the AES does not
    // touch: locator/valuator/choice keep the `vdimouse_init` default.
    assert_eq!(tt_vqin_mode(DUMP_R2, 16, 4), 1);
    assert_eq!(tt_vqin_mode(DUMP_ALL, 40, 4), 1);
    assert_eq!(tt_vqin_mode(DUMP_ALL, 6, 1), 0);
    assert_eq!(tt_vqin_mode(DUMP_ALL, 38, 2), 0);
    assert_eq!(tt_vqin_mode(DUMP_ALL, 39, 3), 0);

    for (dev, want) in [(1i16, 0i16), (2, 0), (3, 0), (4, 1)] {
        assert_eq!(
            vqin_mode(ctx.handle, dev),
            want,
            "vqin_mode({dev}) after an AES dispatch"
        );
    }
}

/// One raw `vqin_mode` (opcode 115) VDI call on `handle`, returning
/// `INTOUT[0]`. The five arrays and the pointer block are laid out the way
/// `harness::open_workstation` lays them for `v_opnvwk`.
fn vqin_mode(handle: i16, dev: i16) -> i16 {
    let mut contrl = Box::new([0i16; 12]);
    let mut intin = Box::new([0i16; 128]);
    let mut ptsin = Box::new([0i16; 256]);
    let mut intout = Box::new([0i16; 128]);
    let mut ptsout = Box::new([0i16; 256]);

    contrl[0] = 115; // vqin_mode
    contrl[3] = 1; // one intin word
    contrl[6] = handle;
    intin[0] = dev;

    let block = [
        contrl.as_mut_ptr() as u64,
        intin.as_mut_ptr() as u64,
        ptsin.as_mut_ptr() as u64,
        intout.as_mut_ptr() as u64,
        ptsout.as_mut_ptr() as u64,
    ];

    // SAFETY: `block` holds five live pointers to arrays owned here, each
    // longer than the one input and one output word `vqin_mode` touches, and
    // all of them outlive the call.
    unsafe { tos_api::vdi::dispatch(block.as_ptr() as u64, harness::ABI) };
    intout[0]
}

// ── the four pointer buffers: the same bytes as the dumper's ─────────────

/// The harness's four `addr_in` buffers must be **byte for byte** the ones
/// `tosdump/core/record.c`'s `td_aes_buf_fill` lays, or a case measures the
/// buffer instead of the function.
///
/// The four strings are stated in the dumper's own words
/// (`tosdump/core/record.c`: "ABCDEFGH, HIJKLMNO, OPQRSTUV, VWXYZABC") and the
/// shape is stated in `tosdump/core/tosdump.h`: `TD_AES_BUF_TEXT_LEN`
/// printable characters, a NUL, and the same printable pattern to the end as a
/// canary. Both are checked here rather than inferred from a case going green:
/// `aes-m05-addrin.tsv`'s `appl_find` cases answer -1 for *every* name that is
/// not an AES process, so they would pass with the wrong bytes too.
#[test]
fn the_four_pointer_buffers_hold_the_dumper_s_own_bytes() {
    let _g = harness::AES_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let mut pb = harness::Pb::new();
    // Lays them, exactly where `runner_aes.c` calls `lay_buffers`.
    pb.poison();

    for (n, text) in [(0, "ABCDEFGH"), (1, "HIJKLMNO"), (2, "OPQRSTUV"), (3, "VWXYZABC")] {
        let b = harness::buffer_snapshot(n);
        assert_eq!(
            &b[..harness::BUF_TEXT_LEN],
            text.as_bytes(),
            "buffer {n} does not read {text}"
        );
        assert_eq!(b[harness::BUF_TEXT_LEN], 0, "buffer {n} has no NUL at BUF_TEXT_LEN");
        // The canary: the same `'A' + (n * 7 + i) % 26` sequence carries on
        // behind the NUL, so a call that wrote past the string is visible.
        for (i, &got) in b.iter().enumerate().skip(harness::BUF_TEXT_LEN + 1) {
            let want = b'A' + ((n as u32 * 7 + i as u32) % 26) as u8;
            assert_eq!(got, want, "buffer {n} byte {i} is not the canary");
        }
    }
}

/// A planted `addr_in` slot records the buffer **token**, not the address: a
/// buffer's address differs between a TT and a Pi by construction, and
/// recording it would fabricate a difference in every case that uses one
/// (`tosdump/core/tosdump.h`, `TD_AES_ADDR_TOKEN`; `runner_aes.c` step 6).
/// A slot the call *modified* records the modified value instead, which is
/// exactly the difference it is.
#[test]
fn a_planted_addr_in_slot_records_the_buffer_token() {
    use harness::{Kind, Plant};

    let _g = harness::AES_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let mut pb = harness::Pb::new();

    pb.poison();
    pb.plant(&[Plant { kind: Kind::AddrIn, slot: 0, buffer: 2 }]);
    assert_eq!(pb.recorded_addrin(0), harness::ADDR_TOKEN_BASE + 2);
    // An unplanted slot still records the poison, so a seven-column table
    // produces the bytes it always did.
    assert_eq!(pb.recorded_addrin(1), harness::POISON_PTR as u32);

    // Overwrite the slot, as a call that wrote there would: the token is gone
    // and the value is recorded.
    pb.addrin[0] = 0x1234_5678;
    assert_eq!(pb.recorded_addrin(0), 0x1234_5678);

    // A fresh poison clears the plant record, as `plant_buffers` does.
    pb.poison();
    assert_eq!(pb.recorded_addrin(0), harness::POISON_PTR as u32);
}

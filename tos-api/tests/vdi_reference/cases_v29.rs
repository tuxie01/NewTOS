//! V29 (TASK/V29.md, finding VDI-TEXT-003 of
//! `docs/audits/2026-11-06-v18-t2-vdi-text.md`): `v_justified` at a
//! right-angle `vst_rotation`. EmuTOS' `gdp_justified` puts the interword
//! and interchar deltas on the axis of the rotated baseline
//! (`vdi/vdi_text.c:1235-1252`, `:1268-1285`) and hands the run to the same
//! `output_text` as `v_gtext`, with `width = max_x` (`:1288`): the anchor,
//! the glyph rotation and the base advance are `v_gtext`'s (`:408-440`,
//! `vdi/vdi_textblit.c:1331-1342`, `:1402-1432`), and the apply loop adds
//! the deltas after each glyph (`vdi/vdi_text.c:476-492`). Spec:
//! `docs/api/vdi/output/_gdp.md` "Justified-text rendering".
//!
//! Two sources, both from the pinned oracle, EmuTOS 1a7484ab on Hatari
//! Falcon030 truecolor (run
//! `measurements/measurement-2026-11-06-v18-t2/RUNINFO.TXT`):
//! - cases 99/102/105 (900/1800/2700) and the control 108 of
//!   `tosdump/cases/vdi-v18-t2.tsv` (CRC `BEFB79A7`), replayed against
//!   `tosdump/reference/EMUTOS-1a7484ab-VDI-v18t2-falcontc.BIN` (record
//!   index = the case's position among the table's measured lines);
//! - the probe cases T1600–T1632 of `tosdump/probes/vdprobe.c` (`t16`):
//!   'AB CD EF', `max_x` 100 at (320,240), the flags interchar / interword
//!   / both, every non-white screen word of the 240×240 grab rectangle at
//!   (200,120), decoded from `probe/e1/VDPROBE.BIN.gz` of that run (the
//!   maps `probe/maps/327-T1610.txt` … `337-T1632.txt` show the same
//!   pixels). `B` is pen 1 (black, glyph ink), `P` is pen 0 (`0xFFDF`, the
//!   glyph cell's background in replace mode); every other word is the
//!   cleared screen's `0xFFFF`. T1600–T1602 (`chup` 0) are the controls.
//!

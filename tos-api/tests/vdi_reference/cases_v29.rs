// ── probe T1600–T1632: the whole 240×240 rectangle ────────────────────────

/// `(y, x_first, x_last, word)`.
type Span = (i16, i16, i16, u16);

const GRAB_T16: (i16, i16, i16, i16) = (200, 120, 240, 240);

/// After the dumper's reset, `calls` in order; then every screen word of
/// the grab rectangle must be the word of the span it lies in, and
/// `0xFFFF` outside every span.
fn probe(name: &str, calls: &[Call], spans: &[Span]) {
    let _guard = VDI_LOCK.lock().unwrap_or_else(|e| e.into_inner());
    let wk = workstation();
    let mut pb = Pb::new();
    reset_vdi(&mut pb, wk);
    for p in calls {
        pb.contrl.fill(0);
        pb.intin[..p.intin.len()].copy_from_slice(p.intin);
        pb.ptsin[..p.ptsin.len()].copy_from_slice(p.ptsin);
        pb.contrl[0] = p.opcode;
        pb.contrl[1] = (p.ptsin.len() / 2) as i16;
        pb.contrl[3] = p.intin.len() as i16;
        pb.contrl[5] = p.sub;
        pb.contrl[6] = wk.handle;
        pb.call();
    }
    let (gx, gy, gw, gh) = GRAB_T16;
    let mut diffs = Vec::new();
    for y in gy..gy + gh {
        for x in gx..gx + gw {
            let want = spans
                .iter()
                .find(|&&(sy, x0, x1, _)| sy == y && (x0..=x1).contains(&x))
                .map_or(WHITE, |&(_, _, _, w)| w);
            let got = screen_word(x, y);
            if got != want {
                diffs.push(format!("({x},{y}) got {got:#06x} want {want:#06x}"));
            }
        }
    }
    assert!(
        diffs.is_empty(),
        "{name}: {} pixels differ from the oracle probe, first: {:?}",
        diffs.len(),
        &diffs[..diffs.len().min(8)]
    );
}


//! V31 (TASK/V31.md, findings VDI-TEXT-007/008 of
//! `docs/audits/2026-11-06-v18-t2-vdi-text.md`): the horizontal DDA of
//! scaled text against the pinned oracle.
//!
//! - **007:** a character wholly outside the clip window is not scaled:
//!   `text_blt` asks `check_clip` before `scale()` and on `-1` jumps to
//!   `upda_dst` (`vdi/vdi_textblit.c:1344-1346`), so `scale()`'s spacing
//!   loop, the only place `XDDA` moves (`:722-733`), does not run for it. The
//!   pen still advances by `char_resize(XDDA, DELX)` (`:1305-1307`,
//!   `:1404-1407`), which reads `XDDA` and leaves it.
//! - **008 (K14):** at an exact double (`dda_inc == 0xFFFF`) `char_resize`
//!   returns `size << 1` (`:1261-1263`), but `scale()` runs its spacing loop
//!   anyway and keeps the sum in `XDDA`: each character takes `XDDA` down by
//!   its `DELX`, from 32767 (`vdi/vdi_text.c:457`). `scaleup` seeds every row
//!   with `XDDA` (`:587`), so the character that finds it at less than `DELX`
//!   does not double one source column, and `scale()` gives it one pixel
//!   less width; the pen still moves 16 (user decision 2026-11-06: as EmuTOS).
//!
//! Sources, all from the pinned oracle, EmuTOS 1a7484ab on Hatari Falcon030
//! truecolor:
//! - cases 86/90/94 of `tosdump/cases/vdi-v18-t2.tsv` (CRC `BEFB79A7`),
//!   replayed against `tosdump/reference/EMUTOS-1a7484ab-VDI-v18t2-falcontc.BIN`
//!   (record = the case's position among the table's measured lines), run
//!   `measurements/measurement-2026-11-06-v18-t2/RUNINFO.TXT`;
//! - the probe cases T14A, T14D–T14F, T14I–T14K, T14M of
//!   `tosdump/probes/vdprobe.c` (`t14`), every non-white screen word of each
//!   grab, decoded from `probe/e1/VDPROBE.BIN.gz` of that run;
//! - the probe cases T31A–T31E (`t31`, added by V31 for `v_justified`, the
//!   right angles and the scale-down DDA), decoded from
//!   `probe/e1/VDPROBE.BIN.gz` of `measurements/measurement-2026-11-07-v31/RUNINFO.TXT`.
//!
//! `B` is pen 1 (black), `P` pen 0 (`0xFFDF`, a cell's background in replace
//! mode), every other word the cleared screen's `0xFFFF`. Hand-written, like
//! `cases_v20`..`cases_v30`; the spans by that run's `method/gen-spans.py`.


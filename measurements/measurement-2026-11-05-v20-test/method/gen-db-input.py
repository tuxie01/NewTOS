#!/usr/bin/env python3 -I
"""gen-db-input.py <out-dir> -- mouse script + shot schedule of tosdump/probes/dbprobe.c (written as dbprobe-mouse.txt /
dbprobe-shots.txt). Pin never crosses the menu bar (left along the row, then up along x = 0)."""
import sys, os
out = sys.argv[1]
lines = []; shots = []
pos = [0, 0]; btn = [False]; t = [100]
def pkt(b, dx, dy): lines.append((t[0], 0xF8 | (2 if b else 0), dx & 255, dy & 255))
def move(x, y, step=30, dt=3):
    while (pos[0], pos[1]) != (x, y):
        dx = max(-step, min(step, x - pos[0])); dy = max(-step, min(step, y - pos[1]))
        pkt(btn[0], dx, dy); pos[0] += dx; pos[1] += dy; t[0] += dt
def press(): btn[0] = True; pkt(True, 0, 0); t[0] += 150
def release(): btn[0] = False; pkt(False, 0, 0); t[0] += 100
def shot(name): t[0] += 100; shots.append((t[0], name)); t[0] += 60
for i in range(5): pkt(False, -127, 0); t[0] += 1
for i in range(3): pkt(False, 0, -127); t[0] += 1
t[0] += 200
for name, ty in (("S0-inside", 100), ("T1-top-17", 3), ("T2-top-18", 2), ("B1-bottom-498", 478), ("B2-bottom-497", 477)):
    move(330, 220); press(); move(330, ty); shot(name); release()
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "dbprobe-mouse.txt"), "w") as f:
    f.write("# dbprobe-mouse.txt -- mouse input of tosdump/probes/dbprobe.c; generated by\n# measurements/measurement-2026-11-05-v20-test/method/gen-db-input.py.\n# <ticks> <0xF8|buttons> <dx> <dy>: one IKBD relative mouse packet per line (bit 1 = left).\n")
    for l in lines: f.write("%d 0x%02x 0x%02x 0x%02x\n" % l)
with open(os.path.join(out, "dbprobe-shots.txt"), "w") as f:
    f.write("# dbprobe-shots.txt -- screenshot schedule of tosdump/probes/dbprobe.c (<ticks> <name>); generated by gen-db-input.py.\n")
    for tk, n in shots: f.write("%d %s\n" % (tk, n))
print(len(lines), "packets,", len(shots), "shots, last tick", t[0])

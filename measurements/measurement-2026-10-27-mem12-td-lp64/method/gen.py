#!/usr/bin/env python3
"""gen.py (copied from measurements/measurement-2026-10-17-rst01/method/gen.py, + shift)
gen.py <spec> <out.script> -- IKBD script generator for tools/inject-arm.py.
spec lines (# comments):
  at <ticks>            set the clock (absolute offset from the arm trigger)
  park                  six (-128,+127) packets: pointer to the bottom-left corner (0,479); never crosses the menu bar
  move X Y [dt]         relative packets of <=127 per axis, one packet every dt ticks (default 5), pointer tracked 1:1 (cal: desk62)
  nop                   one zero-motion packet (a byte to hang a mark on)
  down / up             left button press / release (0xFA / 0xF8 packet)
  click                 down, 10 ticks, up
  dclick                click, 30 ticks, click (one 'click' = 0xFA..0xF8; AES double-click window is long enough at 200 Hz)
  ctrl <make>           Ctrl held around <make> (make/break)
  shift <make>          left Shift held around <make> (make/break) [MEM12 addition]
  key <make> [<break>]  IKBD scancodes (break defaults to make|0x80), 10 ticks apart
  wait <ticks>          advance the clock
  mark NAME             record the tick of the last injected byte in <out>.marks (a screendump is keyed to that byte's feed line)
"""
import sys
t = 0; px = 0; py = 479; out = []; marks = []; last = 0
def emit(*bs):
    global last; last = t
    out.append("%d %s" % (t, " ".join("0x%02X" % (b & 255) for b in bs)))
def clamp(v, lo, hi): return max(lo, min(hi, v))
for l in open(sys.argv[1]):
    l = l.split('#')[0].split()
    if not l: continue
    c = l[0]
    if c == 'at': t = int(l[1])
    elif c == 'wait': t += int(l[1])
    elif c == 'mark': marks.append((l[1], last))
    elif c == 'park':
        for _ in range(6): emit(0xF8, 0x80, 0x7F); t += 3
        px, py = 0, 479
    elif c == 'move':
        X, Y = int(l[1]), int(l[2]); dt = int(l[3]) if len(l) > 3 else 5
        dx, dy = X - px, Y - py
        while dx or dy:
            sx = clamp(dx, -127, 127); sy = clamp(dy, -127, 127)
            emit(0xF8, sx, sy); dx -= sx; dy -= sy; t += dt
        px, py = X, Y
    elif c == 'nop': emit(0xF8, 0, 0); t += 2
    elif c == 'down': emit(0xFA, 0, 0); t += 10
    elif c == 'up': emit(0xF8, 0, 0); t += 10
    elif c == 'click': emit(0xFA, 0, 0); t += 10; emit(0xF8, 0, 0); t += 20
    elif c == 'dclick':
        for _ in range(2): emit(0xFA, 0, 0); t += 8; emit(0xF8, 0, 0); t += 12
        t += 20
    elif c == 'ctrl':
        mk = int(l[1], 0); emit(0x1D); t += 8; emit(mk); t += 8; emit(mk | 0x80); t += 8; emit(0x9D); t += 20
    elif c == 'shift':
        mk = int(l[1], 0); emit(0x2A); t += 8; emit(mk); t += 8; emit(mk | 0x80); t += 8; emit(0xAA); t += 20
    elif c == 'key':
        mk = int(l[1], 0); bk = int(l[2], 0) if len(l) > 2 else mk | 0x80
        emit(mk); t += 10; emit(bk); t += 20
    else: sys.exit("unknown " + c)
open(sys.argv[2], 'w').write("# generated by gen.py from %s\n" % sys.argv[1] + "\n".join(out) + "\n")
open(sys.argv[2] + '.marks', 'w').write(''.join('%s %d\n' % m for m in marks))
print("%d lines, last tick %d, pointer end (%d,%d)" % (len(out), t, px, py))

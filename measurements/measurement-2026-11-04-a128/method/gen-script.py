#!/usr/bin/env python3
"""gen-script.py -- writes s-main.script, the injector input of run `main`
(raspi4b, tools/inject-arm.py launch:FSPROBE). Absolute targets on the
640x480 screen are turned into relative IKBD mouse packets (0xF8|buttons dx dy,
dy > 0 = down; left button = 0x02) from the parked pointer at (0,0); wheel
detents are the IKBD scancodes 0x59 (up) / 0x5A (down), which kernel/src/ikbd.rs
hands to mousexvec like a USB wheel report.

FSELECTR geometry measured on run cal (root at (160,71)): FILEBOX 184..337 x
198..373, FSVSLID 339..362 x 220..351, FDNAROW 341..360 x 356..371, Cancel
291..362 x 393..408."""
import sys
out = []; pos = [None, None]; t = [0]
def at(tick): t[0] = tick
def raw(*b):
    out.append(f"{t[0]} " + " ".join(f"0x{x & 0xff:02X}" for x in b)); t[0] += 1
def park():
    for _ in range(6): raw(0xF8, -127, -127)
    pos[0], pos[1] = 0, 0
def move(x, y, btn=0):
    while (pos[0], pos[1]) != (x, y):
        dx = max(-127, min(127, x - pos[0])); dy = max(-127, min(127, y - pos[1]))
        raw(0xF8 | btn, dx, dy); pos[0] += dx; pos[1] += dy
def press(): raw(0xFA, 0, 0)
def release(): raw(0xF8, 0, 0)
def click(x, y, hold=20):
    move(x, y); press(); t[0] += hold; release()
def wheel(code, n):
    for _ in range(n): raw(code); t[0] += 10
steps = []
def label(s): out.append(f"# +{t[0]}: {s}")

at(600); label("park at (0,0)"); park()
at(1000); label("A: click in the track below the thumb (350,320) -> page down 9"); click(350, 320)
at(1600); label("B: press on the thumb (350,280), drag 40 px down in 4 steps, hold 4 s, release"); move(350, 280); press()
for _ in range(4): t[0] += 20; raw(0xFA, 0, 10); pos[1] += 10
t[0] += 800; release()
at(3000); label("C: wheel up x3 over the list (250,280)"); move(250, 280); t[0] += 20; wheel(0x59, 3)
at(3600); label("D: wheel down x3 outside, over the drive buttons (420,250) -> dropped"); move(420, 250); t[0] += 20; wheel(0x5A, 3)
at(4200); label("E: wheel down x2 over the track (350,330)"); move(350, 330); t[0] += 20; wheel(0x5A, 2)
at(4600); label("E2: three wheel-down detents in ONE injector step over the list (250,300) -> one take of 3"); move(250, 300); t[0] += 20; raw(0x5A, 0x5A, 0x5A)
at(5200); label("F: select the file in row 1 (250,221)"); click(250, 221)
at(5800); label("G: click the down arrow (350,363) -> scroll 1 to the end, selection dropped"); click(350, 363)
at(6400); label("H: select row 2 (250,237), then wheel down x1 over the list at the end -> no move, selection kept"); click(250, 237); t[0] += 200; move(250, 300); t[0] += 20; wheel(0x5A, 1)
at(7200); label("H2: wheel up x1 over the list -> scroll 1, selection dropped"); wheel(0x59, 1)
at(7800); label("I: Cancel (326,400)"); click(326, 400)
open(sys.argv[1], "w").write("# a128 run main -- generated by gen-script.py\n" + "\n".join(out) + "\n")

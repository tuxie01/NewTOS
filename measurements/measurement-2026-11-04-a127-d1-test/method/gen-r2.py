#!/usr/bin/env python3 -I
"""gen-r2.py -- writes r2.script: double-click then menu, dialog, keyboard for A127 D1 (raspi4b, 640x480).
Absolute pointer positions are tracked from the parked corner (0,479); relative IKBD packets
are split at +-127. Ticks are 200 Hz after 'desktop up'."""
import sys
x, y = 0, 479
out = []
def b(v): return v & 0xFF
def pkt(t, btn, dx, dy): out.append(f"{t} {btn:#04x} {b(dx):#04x} {b(dy):#04x}")
def move(t, nx, ny, btn=0xF8):
    global x, y
    dx, dy = nx - x, ny - y
    while dx or dy:
        sx = max(-127, min(127, dx)); sy = max(-127, min(127, dy))
        pkt(t, btn, sx, sy); dx -= sx; dy -= sy; t += 1
    x, y = nx, ny
    return t
def press(t): pkt(t, 0xFA, 0, 0)
def rel(t): pkt(t, 0xF8, 0, 0)
def key(t, *codes):
    for i, c in enumerate(codes): out.append(f"{t+i} {c:#04x}")
# park corner
for i in range(4): pkt(400 + i, 0xF8, -127, 127)
x, y = 0, 479
move(420, 85, 479); move(440, 85, 0)            # File drop-down opens (no window yet: close it)
move(1000, 400, 300)                             # out of the box
press(1400); rel(1420)                           # click outside = cancel
move(2400, 36, 36)                               # Hard disk icon
press(2800); rel(2840); press(2880); rel(2920)   # double-click (80 ms press-to-press) opens C:\
move(3500, 85, 0)                                # ~290 ms after the double-click: into the bar
move(3520, 85, 91)                               # "New folder..."
press(3540); rel(3560)                           # click
move(5000, 390, 291)                             # dialog "Cancel"
press(5200); rel(5220)
move(6000, 36, 36)                               # again: double-click, menu click at once
press(6400); rel(6440); press(6480); rel(6520)
move(6530, 85, 0)
move(6540, 85, 91)
press(6550); rel(6570)                           # New folder within ~30 ms of the double-click
move(8000, 390, 291)                             # dialog Cancel
press(8200); rel(8220)
key(9000, 0x1D, 0x31, 0xB1, 0x9D)                # ^N New folder (keyboard shortcut)
open(sys.argv[1], "w").write("# generated by gen-r2.py (A127 D1 test)\n" + "\n".join(out) + "\n")

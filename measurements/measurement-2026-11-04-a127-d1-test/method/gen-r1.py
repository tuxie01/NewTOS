#!/usr/bin/env python3 -I
"""gen-r1.py -- writes r1.script: desktop-menu regression for A127 D1 (raspi4b, 640x480).
Absolute pointer positions are tracked from the parked corner (0,479); relative IKBD packets
are split at +-127. Ticks are 200 Hz after 'desktop up'."""
import sys
x, y = 0, 479
out = []
def b(v): return v & 0xFF
def pkt(t, btn, dx, dy): out.append(f"{t} {btn:#04x} {b(dx):#04x} {b(dy):#04x}")
def move(t, nx, ny, btn=0xF8):
    global x, y
    dx, dy = nx - x, ny - y
    while dx or dy:
        sx = max(-127, min(127, dx)); sy = max(-127, min(127, dy))
        pkt(t, btn, sx, sy); dx -= sx; dy -= sy; t += 1
    x, y = nx, ny
    return t
def press(t): pkt(t, 0xFA, 0, 0)
def rel(t): pkt(t, 0xF8, 0, 0)
def key(t, *codes):
    for i, c in enumerate(codes): out.append(f"{t+i} {c:#04x}")
# park corner
for i in range(4): pkt(400 + i, 0xF8, -127, 127)
x, y = 0, 479
move(420, 85, 479); move(440, 85, 0)            # File drop-down opens
move(1000, 40, 0)                                # Desk
move(1600, 135, 0)                               # View
move(2200, 190, 0)                               # Options
move(2800, 85, 0)                                # File again
move(3400, 85, 155)                              # hover "Select all items"
press(3600); rel(3620)                           # click-select
move(4400, 85, 0)                                # back up into the bar: File opens
press(5000)                                      # press on the title
move(5020, 85, 123, btn=0xFA)                    # drag onto "Close top window"
rel(5200)                                        # release = select
move(6000, 85, 0)                                # File opens again
move(6600, 400, 300)                             # out of the box (no man's land)
press(7200); rel(7220)                           # click outside = cancel
move(8000, 36, 36)                               # Hard disk icon
press(8200); rel(8210); press(8220); rel(8230)   # double-click opens C:\
move(8240, 85, 0)                                # bar right after the double-click
move(8245, 85, 155)                              # "Select all items"
press(8250); rel(8260)                           # click right after the double-click
key(9000, 0x1D, 0x31, 0xB1, 0x9D)                # ^N New folder (keyboard shortcut)
open(sys.argv[1], "w").write("# generated by gen-r1.py (A127 D1 test)\n" + "\n".join(out) + "\n")

#!/usr/bin/env python3 -I
"""gen-q2.py -- writes q2.script: QED menus (640x480) for A127 D1 (raspi4b, 640x480).
Absolute pointer positions are tracked from the parked corner (0,479); relative IKBD packets
are split at +-127. Ticks are 200 Hz after 'desktop up'."""
import sys
x, y = 0, 479
out = []
def b(v): return v & 0xFF
def pkt(t, btn, dx, dy): out.append(f"{t} {btn:#04x} {b(dx):#04x} {b(dy):#04x}")
def move(t, nx, ny, btn=0xF8):
    global x, y
    dx, dy = nx - x, ny - y
    while dx or dy:
        sx = max(-127, min(127, dx)); sy = max(-127, min(127, dy))
        pkt(t, btn, sx, sy); dx -= sx; dy -= sy; t += 1
    x, y = nx, ny
    return t
def press(t): pkt(t, 0xFA, 0, 0)
def rel(t): pkt(t, 0xF8, 0, 0)
def key(t, *codes):
    for i, c in enumerate(codes): out.append(f"{t+i} {c:#04x}")
# park corner
for i in range(4): pkt(400 + i, 0xF8, -127, 127)
x, y = 0, 479
move(420, 80, 479); move(440, 80, 0)             # Datei opens
move(1000, 80, 27)                               # "Neuer Text"
press(1200); rel(1240)                           # click (40 ms hold)
move(2000, 230, 0)                               # Fenster opens
press(2400)                                      # press on the title
move(2420, 230, 43, btn=0xFA)                    # drag onto "Schliessen"
rel(2600)                                        # release = select (closes the text window)
move(3200, 80, 0)                                # Datei opens
move(3800, 400, 300)                             # out of the box
press(4200); rel(4240)                           # click outside = cancel
move(4600, 80, 0)                                # Datei again
move(4800, 80, 59)                               # no click: just hover "Oeffnen"... then leave through the bar
move(5400, 80, 0)
move(5600, 300, 300)                             # leave the bar (START->track ends)
key(6000, 0x1D, 0x31, 0xB1, 0x9D)                # ^N Neuer Text (keyboard shortcut)
open(sys.argv[1], "w").write("# generated by gen-q2.py (A127 D1 test)\n" + "\n".join(out) + "\n")

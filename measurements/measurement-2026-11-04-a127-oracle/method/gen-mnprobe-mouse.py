#!/usr/bin/env python3 -I
"""gen-mnprobe-mouse.py <out> -- writes tosdump/probes/mnprobe-mouse.txt, the mouse input of
tosdump/probes/mnprobe.c (TASK/A127 D1). IKBD relative packets `0xF8|buttons dx dy`
(bit 1 = left), 200 Hz ticks from the input clock's start; positions tracked from the
corner (0,0) the pointer is pinned to first. Geometry: mnprobe.c build_tree."""
import sys
x = y = 0
out = []
def b(v): return v & 0xFF
def pkt(t, btn, dx, dy, note=""):
    out.append(f"{t} {btn:#04x} {b(dx):#04x} {b(dy):#04x}" + (f"   # {note}" if note else ""))
def move(t, nx, ny, btn=0xF8, note=""):
    global x, y
    dx, dy = nx - x, ny - y
    first = True
    while dx or dy:
        sx = max(-127, min(127, dx)); sy = max(-127, min(127, dy))
        pkt(t, btn, sx, sy, note if first else ""); first = False
        dx -= sx; dy -= sy; t += 1
    x, y = nx, ny
    return t
REST = (300, 300); TITLE = (88, 8); IX = 100
ITEM = {"A": 26, "B": 42, "C": 58, "D": 74}
for i in range(6): pkt(600 + i, 0xF8, -127, -127, "pin to (0,0)" if i == 0 else "")
move(620, *REST, note="rest (300,300)")
segs = [("click", "A", "D2"), ("click", "B", "M"), ("drag", "C", "D2"), ("drag", "D", "M"), ("click", "A", "D1")]
t = 1000
for s, (kind, item, mode) in enumerate(segs):
    for r in range(5):
        tag = f"seg {s} rep {r} {kind} Item {item} (mode {mode})"
        move(t, *TITLE, note=f"{tag}: onto File title")
        if kind == "click":
            move(t + 60, IX, ITEM[item], note=f"onto Item {item}")
            pkt(t + 120, 0xFA, 0, 0, "PRESS")
            pkt(t + 130, 0xF8, 0, 0, "RELEASE")
        else:
            pkt(t + 60, 0xFA, 0, 0, "PRESS on title")
            move(t + 80, IX, ITEM[item], btn=0xFA, note=f"drag onto Item {item}")
            pkt(t + 120, 0xF8, 0, 0, "RELEASE")
        move(t + 400, *REST, note="back to rest")
        t += 500
hdr = ("# mnprobe-mouse.txt -- the mouse input of tosdump/probes/mnprobe.c (TASK/A127 D1); generated by\n"
       "# measurements/measurement-2026-11-04-a127-oracle/method/gen-mnprobe-mouse.py.\n"
       "# <ticks> <0xF8|buttons> <dx> <dy>: one IKBD relative mouse packet per line (bit 1 = left).\n"
       "# NewTOS: tools/inject-arm.py launch:MNPROBE; EmuTOS: the probe's own feeder (C:\\MNPROBE.INJ).\n")
open(sys.argv[1], "w").write(hdr + "\n".join(out) + "\n")

#!/usr/bin/env python3 -I
"""gen-fifo.py <out-fifo> <out-inj> -- the --cmd-fifo cross-check of run-mnprobe.sh (A127 oracle):
pointer and left button through EmuTOS's Alt-arrow / Alt-Insert mouse emulation (8 px per
Alt+arrow make, bios/ikbd.c:285-389). <pause ms> keydown|keyup <scancode>. Alt is held
throughout. Pin to (0,0), File title = (88,8), Item A = (88,24), rest = (88,200).
5 reps for the probe's seg 0 (mode D2), 5 for seg 1 (mode M): click-select, Item A."""
import sys
ALT, LEFT, RIGHT, UP, DOWN, INS = 56, 75, 77, 72, 80, 82
out = []
def ev(ms, what, code, note=""): out.append(f"{ms} {what} {code}" + (f"   # {note}" if note else ""))
def steps(code, n, note=""):
    for i in range(n):
        ev(40, "keydown", code, note if i == 0 else ""); ev(40, "keyup", code)
ev(0, "keydown", ALT, "Alt held")
steps(LEFT, 85, "pin left"); steps(UP, 65, "pin up")
steps(DOWN, 25, "y 200 (outside the bar)"); steps(RIGHT, 11, "rest (88,200)")
for r in range(10):
    steps(UP, 24, f"rep {r}: up to the File title (88,8)")
    ev(600, "keydown", DOWN, "onto Item A (88,24)"); ev(40, "keyup", DOWN)
    ev(40, "keydown", DOWN); ev(40, "keyup", DOWN)
    ev(500, "keydown", INS, "PRESS (Alt+Insert)"); ev(60, "keyup", INS, "RELEASE")
    ev(1500, "keydown", DOWN, "down to rest (88,200)"); ev(40, "keyup", DOWN)
    steps(DOWN, 21)
ev(500, "keyup", ALT, "Alt released")
open(sys.argv[1], "w").write("# generated by gen-fifo.py (A127 oracle cross-check)\n" + "\n".join(out) + "\n")
open(sys.argv[2], "w").write("# empty: the probe feeds nothing in the --cmd-fifo cross-check\n")

#!/usr/bin/env python3
"""mkreplay.py SERIAL_LOG OUT.h -- turn the raw Ssystem(2022) answers a usbsnap-virt.c run dumped (USBSNAP-RAW /
USBSNAP-HEX lines) into C arrays for usbsnap-replay.c: the LIST answer taken right before the recording's MUTE, every
DEVICE answer, every REPORTS entry (80 bytes, unique by device + seq) and the MUTE start tick. Bodies only (the 32-byte
header is rebuilt by the replay)."""
import re, sys
lines = open(sys.argv[1], errors="replace").read().splitlines()
blocks = []
for i, l in enumerate(lines):
    m = re.search(r"USBSNAP-RAW op=(\d+) idx=(\d+) arg=(\d+) rc=(-?\d+) used=(\d+) now=(\d+)", l)
    if m:
        blocks.append(dict(op=int(m[1]), idx=int(m[2]), arg=int(m[3]), rc=int(m[4]), used=int(m[5]), now=int(m[6]), data=bytearray()))
        continue
    m = re.search(r"USBSNAP-HEX ([0-9a-f]+)", l)
    if m and blocks:
        blocks[-1]["data"] += bytes.fromhex(m[1])
first_mute = next(k for k, b in enumerate(blocks) if b["op"] == 4 and b["arg"] > 0)
lst = [b for b in blocks[:first_mute] if b["op"] == 1 and b["used"] > 32][-1]
t0 = blocks[first_mute]["now"]
devs = {}
for b in blocks:
    if b["op"] == 2 and b["rc"] == 0 and b["idx"] not in devs: devs[b["idx"]] = bytes(b["data"][32:b["used"]])
recs = {}
for b in blocks[first_mute:]:
    if b["op"] == 3 and b["rc"] == 0:
        d = b["data"]; cnt = d[32 + 12] | d[32 + 13] << 8; rl = d[32 + 14] | d[32 + 15] << 8
        for k in range(cnt):
            r = bytes(d[48 + k * rl:48 + (k + 1) * rl]); seq = int.from_bytes(r[0:4], "little")
            recs[(b["idx"], seq)] = r
def arr(name, by):
    return f"static const unsigned char {name}[{max(len(by),1)}] = {{" + ",".join(str(x) for x in by) + "};\n"
o = [f"/* generated by mkreplay.py from {sys.argv[1].split('/')[-1]} */\n", f"#define R_T0 {t0}u\n", arr("R_LIST", lst["data"][32:lst["used"]]), f"#define R_LIST_LEN {lst['used'] - 32}\n"]
n = max(devs) + 1 if devs else 0
for i in range(n): o.append(arr(f"R_DEV{i}", devs.get(i, b"")))
o.append(f"#define R_NDEV {n}\nstatic const unsigned char *const R_DEV[{max(n,1)}] = {{" + ",".join(f"R_DEV{i}" for i in range(n)) + "};\n")
o.append(f"static const unsigned R_DEVLEN[{max(n,1)}] = {{" + ",".join(str(len(devs.get(i, b''))) for i in range(n)) + "};\n")
keys = sorted(recs)
o.append(f"#define R_NREC {len(keys)}\nstatic const unsigned char R_RECIDX[{max(len(keys),1)}] = {{" + ",".join(str(k[0]) for k in keys) + "};\n")
o.append(f"static const unsigned char R_REC[{max(len(keys),1)}][80] = {{" + ",".join("{" + ",".join(str(x) for x in recs[k]) + "}" for k in keys) + "};\n")
open(sys.argv[2], "w").write("".join(o))
print(f"LIST {lst['used']} bytes (now {lst['now']}), MUTE t0 {t0}, devices {sorted(devs)}, records {len(keys)} " +
      str({i: sum(1 for k in keys if k[0] == i) for i in sorted(set(k[0] for k in keys))}))

#!/usr/bin/env python3 -I
"""gen-flicker-input.py <mouse-out> <shots-emutos> <shots-newtos> -- the flicker run of slprobe.c
(TASK/A130): the elevator is pressed and the pointer is then moved OFF the bar into the work area
while the button stays down (the drag goes on; for size 1000 the elevator cannot move), so the
elevator area holds no pointer. During each 2 s hold the screen is sampled: EmuTOS every 40 ticks
(the Hatari capture needs >= 30 ticks between shots), NewTOS every 10 ticks (QMP screendump).
Holds: H1 size 1000 vertical, H2 size 1000 horizontal, H3 size 300 vertical, H4 size -1 vertical;
then one sample 'idle' of each configuration with the button up (control: nothing pressed)."""
import sys

pk = []
x = y = 0
t = 0
btn = 0xF8
shots_e, shots_n = [], []


def b(v):
    return v & 0xFF


def pkt(tk, bt, dx, dy, note=""):
    pk.append(f"{tk} {bt:#04x} {b(dx):#04x} {b(dy):#04x}" + (f" # {note}" if note else ""))


def move(nx, ny, step=127, every=1, note=""):
    global x, y, t
    dx, dy = nx - x, ny - y
    first = True
    while dx or dy:
        sx = max(-step, min(step, dx))
        sy = max(-step, min(step, dy))
        pkt(t, btn, sx, sy, note if first else "")
        first = False
        dx -= sx
        dy -= sy
        t += every
    x, y = nx, ny


def press(note=""):
    global btn, t
    btn = 0xFA
    pkt(t, btn, 0, 0, "PRESS " + note)
    t += 1


def release(note=""):
    global btn, t
    btn = 0xF8
    pkt(t, btn, 0, 0, "RELEASE " + note)
    t += 1


def sample(tag, length=400):
    """Samples over `length` ticks starting 40 ticks from now."""
    global t
    t += 40
    for i in range(0, length, 40):
        shots_e.append((t + i, f"{tag}-e{i // 40:02d}"))
    for i in range(0, length, 10):
        shots_n.append((t + i, f"{tag}-n{i // 10:02d}"))
    t += length + 40


def config(cx):
    global t
    move(cx, 200)
    press("config")
    t += 10
    release()
    t += 120


for i in range(6):
    pkt(600 + i, 0xF8, -127, 127, "pin to (0,479)" if i == 0 else "")
y = 479
t = 620
move(560, 440, note="rest")
t += 100
sample("idle1000", 80)
# H1: size 1000 (the start configuration), vertical
move(468, 220, note="H1 onto the V elevator")
press("H1 V elevator")
t += 100  # v2: still beyond the double-click wait before moving off the bar
move(300, 220, step=8, every=2, note="H1 off the bar into the work area, held")
sample("h1-1000-V")
release("H1")
t += 200
# H2: size 1000, horizontal
move(268, 368, note="H2 onto the H elevator")
press("H2 H elevator")
t += 100  # v2: still beyond the double-click wait before moving off the bar
move(268, 250, step=8, every=2, note="H2 off the bar into the work area, held")
sample("h2-1000-H")
release("H2")
t += 200
# H3: size 300, vertical
config(220)
move(560, 440)
t += 60
sample("idle300", 80)
move(468, 220, note="H3 onto the V elevator")
press("H3 V elevator")
t += 100  # v2: still beyond the double-click wait before moving off the bar
move(300, 220, step=8, every=2, note="H3 off the bar, held")
sample("h3-300-V")
release("H3")
t += 200
# H4: size -1, vertical
config(310)
move(560, 440)
t += 60
sample("idlemin", 80)
move(468, 219, note="H4 onto the V elevator")
press("H4 V elevator")
t += 100  # v2: still beyond the double-click wait before moving off the bar
move(300, 219, step=8, every=2, note="H4 off the bar, held")
sample("h4-min-V")
release("H4")
t += 200
move(420, 200, note="quit")
press("quit")
t += 10
release()

hdr = ("# slprobe flicker input (TASK/A130); generated by\n"
       "# measurements/measurement-2026-11-05-a130/method/gen-flicker-input.py.\n")
open(sys.argv[1], "w").write(hdr + "\n".join(pk) + "\n")
for path, sh in ((sys.argv[2], shots_e), (sys.argv[3], shots_n)):
    open(path, "w").write(hdr + "".join(f"{tk} {n}\n" for tk, n in sh))
print(f"{len(pk)} packets, {len(shots_e)} / {len(shots_n)} shots, last tick {t}", file=sys.stderr)

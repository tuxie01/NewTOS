//! A40 — `tools/mkrsc.py convert` must leave the OBJECT coordinates as the
//! **packed char-grid words** the classic file holds; the char→pixel fix is
//! the loader's, at load time, with the live font cell and screen width.
//!
//! EmuTOS converts on load (`references/emutos/aes/gemrslib.c:53-99`,
//! `fix_chpos`/`rs_obfix`, run over every object by `fix_objects` `:606-637`
//! from `rs_fixit` `:816-820`) with `gl_wchar`/`gl_hchar`/`gl_width` — the
//! values of the machine the resource is loaded on. The tool used to do that
//! arithmetic itself with `WCHAR, HCHAR, SCREEN_W = 8, 16, 640` baked in
//! (audit B10, `docs/analysis/audit-applinit-rsrc-load-2026-09-11.md`), so
//! every converted resource carried the pixels of a 640-wide 8×16 screen.
//!
//! The reference here is EmuTOS's own `aes/gem.rsc`: its DESKTOP tree
//! (tree 2, root object 63) is the textbook 80-character-wide root —
//! `ob_width = 0x0050` — whose width EmuTOS turns into `gl_width` at load
//! (`gemrslib.c:71-74`). The converter wrote **640** there. The tests below
//! drive the real tool over that file in both NRSC modes and compare every
//! object's four words against the classic file, byte-swapped and nothing
//! else; the committed `gem_fsel.nrsc` (regenerated by `cargo xtask
//! gen-fsel-rsc`) is held to the same shape so a stale artifact cannot
//! outlive the tool change. The native-RSHDR mode (`--rshdr`, for an
//! application's *own* loader, which runs its own `rsc_obfix`) always kept
//! the raw words and is unchanged.
//!
//! Ticket: `TASK/A40.md`. The loader half is `tos-api/tests/aes_rsrc_obfix_at_load.rs`.

use std::path::{Path, PathBuf};
use std::process::Command;

use crate::workspace_root;

/// First NRSC `version` whose OBJECT coordinates are packed char-grid words
/// (v9 LP64, v10 ILP32; `tos-api/src/aes/resource.rs::NRSC_VER_CHARGRID`).
const NRSC_VER_CHARGRID: u32 = 9;

/// EmuTOS's DESKTOP root in `aes/gem.rsc` — object 63, `ob_width` char 80.
const GEM_DESKTOP_ROOT: usize = 63;

fn be16(d: &[u8], o: usize) -> u16 {
    u16::from_be_bytes([d[o], d[o + 1]])
}

fn le16(d: &[u8], o: usize) -> u16 {
    u16::from_le_bytes([d[o], d[o + 1]])
}

fn le32(d: &[u8], o: usize) -> u32 {
    u32::from_le_bytes([d[o], d[o + 1], d[o + 2], d[o + 3]])
}

/// EmuTOS's classic resource, workspace-relative (a gitignored input).
const GEM_RSC: &str = "references/emutos/aes/gem.rsc";

fn gem_rsc_path() -> PathBuf {
    workspace_root().join(GEM_RSC)
}

fn gem_fsel_path() -> PathBuf {
    workspace_root()
        .join("tos-api")
        .join("src")
        .join("aes")
        .join("gem_fsel.nrsc")
}

/// The four coordinate words of every OBJECT of a classic (big-endian)
/// `.rsc`, as unsigned 16-bit values — `rsh_object` + 24·i, words at
/// +16..+22 (`include/obdefs.h` OBJECT).
fn classic_words(d: &[u8]) -> Vec<[u16; 4]> {
    let off_obj = be16(d, 2) as usize; // rsh_object
    let n_obj = be16(d, 20) as usize; // rsh_nobs
    (0..n_obj)
        .map(|i| {
            let o = off_obj + i * 24;
            [
                be16(d, o + 16),
                be16(d, o + 18),
                be16(d, o + 20),
                be16(d, o + 22),
            ]
        })
        .collect()
}

/// `(version, the four coordinate words of every OBJECT)` of an NRSC blob.
/// The record stride and the coordinate offset follow the version's parity
/// (odd = LP64, 32-byte OBJECT with the words at +24; even = ILP32, 24-byte
/// OBJECT with the words at +16).
fn nrsc_words(d: &[u8]) -> (u32, Vec<[u16; 4]>) {
    // The NRSC header sits at the front (v1–v12) or behind the 40-byte native
    // `RSHDR` preamble (v13+, `resource.rs` `RSHDR_PAD`); the offsets it
    // holds count from the file's first byte either way.
    let h = if &d[..4] == b"NRSC" { 0 } else { 40 };
    assert_eq!(&d[h..h + 4], b"NRSC", "not an NRSC blob");
    let version = le32(d, h + 4);
    let n_obj = le32(d, h + 12) as usize;
    let off_obj = le32(d, h + 20) as usize;
    let (stride, at) = if version % 2 == 1 { (32, 24) } else { (24, 16) };
    let words = (0..n_obj)
        .map(|i| {
            let o = off_obj + i * stride + at;
            [le16(d, o), le16(d, o + 2), le16(d, o + 4), le16(d, o + 6)]
        })
        .collect();
    (version, words)
}

/// The tool's output must be a char-grid blob whose words are the classic
/// file's, nothing computed.
fn assert_words_untouched(classic: &[u8], out_path: &Path, out: &[u8]) {
    let want = classic_words(classic);
    let (version, got) = nrsc_words(out);
    assert_eq!(
        got.len(),
        want.len(),
        "{}: object count",
        out_path.display()
    );
    // The one case the audit named first: the 80-character root stays 80
    // characters (`0x0050`), so the loader can make it `gl_width` on *its*
    // screen — the converter wrote the 640 of its baked-in SCREEN_W.
    assert_eq!(
        got[GEM_DESKTOP_ROOT][2],
        0x0050,
        "{}: DESKTOP root ob_width must be the packed 80-character word 0x0050, not a \
         pixel count (got {} = 0x{:04x})",
        out_path.display(),
        got[GEM_DESKTOP_ROOT][2] as i16,
        got[GEM_DESKTOP_ROOT][2]
    );
    for (i, (g, w)) in got.iter().zip(&want).enumerate() {
        assert_eq!(
            g,
            w,
            "{}: object {i}: the coordinate words must be the classic file's packed \
             char-grid words (got {g:04x?}, classic {w:04x?}) — the char→pixel fix is \
             the loader's (gemrslib.c:53-99), not the tool's",
            out_path.display()
        );
    }
    assert!(
        version >= NRSC_VER_CHARGRID,
        "{}: version {version} — a blob whose coordinates are packed char-grid words \
         must declare NRSC v{NRSC_VER_CHARGRID}+ so the loader runs rs_obfix on it",
        out_path.display()
    );
}

fn scratch_dir(name: &str) -> PathBuf {
    let dir = workspace_root()
        .join("target")
        .join("xtask-rsc-obfix")
        .join(name);
    std::fs::create_dir_all(&dir).expect("create scratch dir");
    dir
}

fn run_mkrsc(dir: &Path, mode: Option<&str>, src: &Path, out: &Path) {
    let root = workspace_root();
    let script = root.join("tools").join("mkrsc.py");
    let python = std::env::var_os("PYTHON").unwrap_or_else(|| "python3".into());
    let mut c = Command::new(&python);
    c.current_dir(dir).arg(&script).arg("convert");
    if let Some(m) = mode {
        c.arg(m);
    }
    let st = c
        .arg(src)
        .arg(out)
        .status()
        .unwrap_or_else(|e| panic!("cannot run {python:?} {}: {e}", script.display()));
    assert!(st.success(), "mkrsc.py convert {mode:?} failed with {st}");
}

/// Convert EmuTOS's `gem.rsc` in one NRSC mode and check the words.
fn check_mode(test: &str, tag: &str, mode: Option<&str>) {
    if !crate::test_inputs::require_paths(test, &[GEM_RSC]) {
        return;
    }
    let src = gem_rsc_path();
    let classic = std::fs::read(&src).expect("references/emutos/aes/gem.rsc must exist");
    let dir = scratch_dir(tag);
    let out = dir.join("gem.nrsc");
    run_mkrsc(&dir, mode, &src, &out);
    let d = std::fs::read(&out).expect("read converted resource");
    assert_words_untouched(&classic, &out, &d);
}

#[test]
fn mkrsc_convert_lp64_keeps_the_char_grid_coordinates() {
    check_mode("rsc_obfix_tests::mkrsc_convert_lp64_keeps_the_char_grid_coordinates", "lp64", None);
}

#[test]
fn mkrsc_convert_ilp32_keeps_the_char_grid_coordinates() {
    check_mode("rsc_obfix_tests::mkrsc_convert_ilp32_keeps_the_char_grid_coordinates", "ilp32", Some("--ilp32"));
}

/// The committed blob the kernel embeds (`tos-api/src/aes/fsel.rs`
/// `GEM_FSEL_RSC`) is `gem.rsc` through the same tool — EmuTOS runs
/// `rs_obfix` over its embedded resource too (`gem_rsc_fixit`,
/// `aes/gem_rsc.c:636-641`, `geminit.c:711`).
#[test]
fn the_committed_gem_fsel_blob_carries_char_grid_coordinates() {
    if !crate::test_inputs::require_paths(
        "rsc_obfix_tests::the_committed_gem_fsel_blob_carries_char_grid_coordinates",
        &[GEM_RSC],
    ) {
        return;
    }
    let classic = std::fs::read(gem_rsc_path()).expect("references/emutos/aes/gem.rsc must exist");
    let p = gem_fsel_path();
    let d = std::fs::read(&p).expect("gem_fsel.nrsc must be committed");
    assert_words_untouched(&classic, &p, &d);
}
